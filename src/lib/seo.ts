import type { Fabric } from "@/lib/types";

/**
 * Ключевые запросы взяты из выгрузок Яндекс.Wordstat, которые прислал
 * заказчик (docs/../«СЕО запросы»), а не придуманы.
 *
 * Важно: основная масса запросов по слову «канвас» - это канвас для сумок,
 * рюкзаков и одежды, то есть чужая товарная категория. Поэтому во всех
 * формулировках намеренно оставлено уточнение «портьерный» / «для штор»:
 * оно отсекает нецелевой трафик, который всё равно ничего не купит
 * при минимальном заказе от рулона.
 */
export const siteKeywords = [
  // Оптовые запросы - основная цель, подтверждены частотностью.
  "купить канвас оптом",
  "канвас ткань купить оптом",
  "блэкаут купить оптом",
  "ткань блэкаут купить оптом",
  "портьерная ткань блэкаут купить оптом",
  "где купить канвас оптом",
  "канвас купить оптом от производителя",
  // Портьерное уточнение - отсекает канвас для сумок и одежды.
  "портьерная ткань купить",
  "ткань портьерная канвас купить",
  "купить канвас для штор",
  "канвас для штор купить рулон",
  "ткань для штор оптом",
  // Формат поставки - совпадает с реальной моделью продаж.
  "канвас купить рулон",
  "канвас метражом купить",
  // Происхождение и характеристики.
  "канвас турция купить",
  "канвас плотный купить",
  "канвас блэкаут купить",
] as const;

/**
 * Запросы под конкретную ткань. Собираются по тем же шаблонам, что
 * реально встречаются в Wordstat, но подставляется категория этой ткани.
 */
export function fabricKeywords(fabric: Fabric): string[] {
  const category = fabric.category.toLowerCase();

  return [
    `${category} купить оптом`,
    `ткань ${category} купить оптом`,
    `купить ${category} для штор`,
    `портьерная ткань ${category}`,
    `${category} купить рулон`,
    `${category} ${fabric.origin.toLowerCase()} купить`,
    fabric.name.toLowerCase(),
  ];
}

/** Description для страницы ткани - с характеристиками, они тоже в запросах. */
export function fabricDescription(fabric: Fabric): string {
  return [
    `${fabric.name} оптом от рулона.`,
    `Ширина полотна ${fabric.widthCm} см, плотность ${fabric.densityGsm} г/м²,`,
    `${fabric.colorsCount} оттенков, производство - ${fabric.origin}.`,
    fabric.shortDescription,
  ].join(" ");
}
