import type { UsdRateInfo } from "@/lib/currency";

/**
 * Подпись под ценой: на какой день она посчитана.
 *
 * Раньше здесь стояло «расчёт ориентировочный» - и это было неправдой.
 * Цена настоящая: она пересчитывается из долларов по курсу ЦБ и на
 * сегодняшний день именно такая. Заодно это снимает вопрос «почему вчера
 * было другое число» и само по себе подсказывает не откладывать заказ -
 * без «успейте» и прочего нажима, который оптовика только отталкивает.
 *
 * Если курс от ЦБ получить не удалось, сайт считает по резервному
 * значению. Тогда ссылаться на ЦБ нельзя, и подпись молчит о нём.
 */
export function PriceNote({
  rate,
  className,
}: {
  rate: Pick<UsdRateInfo, "fromCbr">;
  className?: string;
}) {
  if (!rate.fromCbr) {
    return (
      <p className={className}>
        Окончательную стоимость подтверждает менеджер.
      </p>
    );
  }

  /*
   * Дата курса намеренно не показывается, хотя ЦБ её сообщает. После
   * 15:30 МСК он публикует курс, который вступает в силу на следующий
   * день, и подпись «по курсу на 26.09» вечером 25-го выглядит опечаткой.
   * «На сегодня» верно в обоих случаях: это тот курс, который ЦБ считает
   * актуальным, и именно по нему посчитана цена на экране.
   */
  return (
    <p className={className}>
      По курсу ЦБ РФ на сегодня. Пересчёт — ежедневно.
    </p>
  );
}
