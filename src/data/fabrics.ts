/**
 * К каждой ткани подставляется её отснятая палитра, а обложкой становится
 * презентационная фотография, если она есть. Ткани без съёмки остаются
 * с заглушкой - галерея оттенков у них просто не показывается.
 */
/**
 * Какой оттенок снят на презентационном фото - по исходной съёмке
 * (scripts/convert-photos.js, раздел HERO).
 */
const coverCodes: Record<string, string> = {
  kanvas: "114",
  "kanvas-ali": "44",
  satin: "389",
  "satin-ali": "119",
};

export const fabrics: Fabric[] = baseFabrics.map((fabric) => {
  const colors = fabricColors[fabric.slug];
  if (!colors?.length) return fabric;
  return {
    ...fabric,
    image: `/images/fabrics/${fabric.slug}/cover.webp`,
    colors,
    coverCode: coverCodes[fabric.slug],
  };
});

export function getFabricBySlug(slug: string): Fabric | undefined {
  return fabrics.find((fabric) => fabric.slug === slug);
}

export const fabricCategories = Array.from(
  new Set(fabrics.map((fabric) => fabric.category))
);

/**
 * Сколько оттенков во всём каталоге - по товарной матрице. Это самая
 * сильная цифра ассортимента: «8 тканей» звучит бедно, а за ними стоит
 * больше двухсот цветов.
 */
export const totalShades = fabrics.reduce(
  (sum, fabric) => sum + fabric.colorsCount,
  0
);

/**
 * Ткани с настоящей съёмкой. Витрину на главной собираем только из них:
 * заглушка-рулон дважды подряд делала блок похожим на недоделанный.
 */
export const photographedFabrics = fabrics.filter(
  (fabric) => (fabric.colors?.length ?? 0) > 0
);

export const widthOptions = Array.from(
  new Set(fabrics.map((fabric) => fabric.widthCm))
).sort((a, b) => a - b);

export const colorFamilyOptions = Array.from(
  new Set(fabrics.flatMap((fabric) => fabric.colorFamilies))
);

export const priceRange = {
  min: Math.floor(Math.min(...fabrics.map((fabric) => fabric.priceUsd))),
  max: Math.ceil(Math.max(...fabrics.map((fabric) => fabric.priceUsd))),
};
