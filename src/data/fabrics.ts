/**
 * На сайте показываются только ткани с настоящей съёмкой.
 *
 * Пока фотографий нет, ткань выводилась с нарисованным рулоном-заглушкой
 * и рядом с реальными снимками сразу бросалась в глаза - заказчик попросил
 * такие убрать. Ткань вернётся на сайт сама, без правок кода, как только
 * её фотографии появятся в палитре: считается, счётчики, карта сайта и
 * страница ткани строятся из этого же списка.
 */
export const fabrics: Fabric[] = baseFabrics
  .filter((fabric) => (fabricColors[fabric.slug]?.length ?? 0) > 0)
  .map((fabric) => ({
    ...fabric,
    // ?v= - отпечаток содержимого обложки. Имя файла при замене кадра
    // не меняется, а оптимизатор картинок Next кеширует результат по
    // адресу и инвалидировать его нечем: документация советует менять src.
    // Без отпечатка новая обложка несколько часов показывалась бы старой.
    image: `/images/fabrics/${fabric.slug}/cover.webp${
      coverVersions[fabric.slug] ? `?v=${coverVersions[fabric.slug]}` : ""
    }`,
    colors: fabricColors[fabric.slug],
    coverCode: coverCodes[fabric.slug],
  }));

export function getFabricBySlug(slug: string): Fabric | undefined {
  return fabrics.find((fabric) => fabric.slug === slug);
}

export const fabricCategories = Array.from(
  new Set(fabrics.map((fabric) => fabric.category))
);

/**
 * Сколько оттенков во всём каталоге — по товарной матрице. Это самая
 * сильная цифра ассортимента: «8 тканей» звучит бедно, а за ними стоит
 * больше двухсот цветов.
 */
export const totalShades = fabrics.reduce(
  (sum, fabric) => sum + fabric.colorsCount,
  0
);

export const widthOptions = Array.from(
  new Set(fabrics.map((fabric) => fabric.widthCm))
).sort((a, b) => a - b);

export const colorFamilyOptions = Array.from(
  new Set(fabrics.flatMap((fabric) => fabric.colorFamilies))
);

export const priceRange = {
  min: Math.floor(Math.min(...fabrics.map((fabric) => fabric.priceUsd))),
  max: Math.ceil(Math.max(...fabrics.map((fabric) => fabric.priceUsd))),
};
